#ifndef TEARWASH_TWPRESETS_HPP
#define TEARWASH_TWPRESETS_HPP

// Tearwash presets (docs/03_PRESETS.md) [A]. A preset is a name and a value for every
// plugin parameter, the program included; the text format is `.twpreset`:
//
//   # Tearwash preset v1
//   name=SP Teardrops In Neon Rain
//   program=VAST SPACE
//   decay=0.6862745098
//   ...
//
// It is spux's text preset format (spux/state/TextPreset.hpp): keys, not ids, and numbers written
// and read without the C locale. The program is stored by name (it survives list changes); unknown
// keys are ignored, missing keys keep the program's stored settings, values are clamped. Names start with a two-letter
// category code (IN, PG, HL, RM, PL, SP, EC, FX), then the user folder.

#include "TwParams.hpp"

#include <array>
#include <string>
#include <vector>

namespace tearwash {

using TwValues = std::array<double, TW_PARAM_COUNT>;

// Built-in library (TwPresetData.cpp, generated by tools/gen_presets.py): each preset is
// the program as stored, then these values (0…1 as the plugin stores them; the program is given
// separately).
struct TwPresetValue { const char* key; double value; };
struct TwBuiltinPreset {
    const char* name;
    const char* program;
    const TwPresetValue* values;
    int count;
};
extern const TwBuiltinPreset kTwBuiltinPresets[];
extern const int kTwBuiltinPresetCount;

struct TwPreset {
    std::string name;       // "SP Teardrops In Neon Rain"
    std::string category;   // "SP"
    bool user = false;
    std::string path;       // user presets
    TwValues values{};
};

// Parameter defaults, and a program with its stored settings (what selecting it loads).
TwValues twDefaultValues();
TwValues twProgramValues(int program);
// Program index from its name (−1 if absent).
int twProgramIndex(const std::string& name);

bool parsePresetText(const std::string& text, TwValues& values, std::string* name);
std::string presetToText(const TwValues& values, const std::string& name);

class TwPresetLibrary {
public:
    TwPresetLibrary();
    const std::vector<TwPreset>& presets() const { return presets_; }
    int count() const { return static_cast<int>(presets_.size()); }
    int indexOf(const std::string& name) const;
    // Category codes in menu order, only those present, then "USER" when there are user presets.
    std::vector<std::string> categories() const;
    static std::string categoryName(const std::string& code);
    static std::string categoryOf(const std::string& name);
    void scanUserPresets();
    static std::string userPresetDirectory();
    bool saveUserPreset(const std::string& path, const TwValues& values, std::string& name, std::string& error);
private:
    std::vector<TwPreset> presets_;
    int builtinCount_ = 0;
};

} // namespace tearwash

#endif
