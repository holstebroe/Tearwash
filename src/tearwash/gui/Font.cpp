// Row-major copy of the classic font in the same layout as g_font5x7
// (bit 7 = leftmost column).
static uint8_t g_classic5x7[128][7];
static bool g_classicInitialized = false;

static void initClassicTable() {
    if (g_classicInitialized) return;
    std::memset(g_classic5x7, 0, sizeof(g_classic5x7));
    for (int c = 32; c < 96; ++c) {
        for (int col = 0; col < 5; ++col) {
            uint8_t colBits = g_classicColumns[c - 32][col];
            for (int row = 0; row < 7; ++row) {
                if (colBits & (1 << row)) {
                    g_classic5x7[c][row] |= static_cast<uint8_t>(0x80 >> col);
                }
            }
        }
    }
    // Lowercase falls back to uppercase.
    for (int c = 'a'; c <= 'z'; ++c) {
        std::memcpy(g_classic5x7[c], g_classic5x7[c - 'a' + 'A'], 7);
    }
    g_classicInitialized = true;
}

