Font::Font(uint32_t width, uint32_t height, bool classic)
    : width_(width), height_(height), classic_(classic) {
    initFontTable();
    initClassicTable();
}

const uint8_t* Font::getGlyph(char c) const {
    const uint8_t (*table)[7] = classic_ ? g_classic5x7 : g_font5x7;
    uint8_t idx = static_cast<uint8_t>(c);
    if (idx < 128) {
        return table[idx];
    }
    return table[' '];
}

int Font::getTextWidth(const char* text, int scale) const {
    if (!text) return 0;
    size_t len = std::strlen(text);
    return static_cast<int>(len * (width_ + 1)) * scale;
}

Font Font::defaultPanelFont() {
    return Font(7, 7);
}

Font Font::classic5x7() {
    return Font(5, 7, true);
}

