#!/usr/bin/env python3
"""Generate src/tearwash/plugin/TwPresetData.cpp from tools/preset_library.py.

Validates parameter keys against src/tearwash/plugin/TwParams.cpp and program names against
src/tearwash/engine/Reverb.cpp, applies the loudness trims in tools/preset_gains.json
(as the output gain, dB; build/tearwash_preset_test --fit writes them) and writes the C++ table.
usage: python3 tools/gen_presets.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import preset_library as lib  # noqa: E402


def param_keys():
    src = open(os.path.join(ROOT, 'src/tearwash/plugin/TwParams.cpp')).read()
    return re.findall(r'\{ "([a-z0-9]+)",\s+"', src)


def program_names():
    src = open(os.path.join(ROOT, 'src/tearwash/engine/Reverb.cpp')).read()
    return re.findall(r'^    \{ "([A-Z ]+)", [01],', src, re.M)


def main():
    keys = set(param_keys())
    programs = set(program_names())
    if len(programs) < 2:
        sys.exit('could not read the program names')
    gains_path = os.path.join(ROOT, 'tools/preset_gains.json')
    gains = json.load(open(gains_path)) if os.path.exists(gains_path) else {}
    names = set()
    out = ['// Generated by tools/gen_presets.py from tools/preset_library.py. Do not edit.',
           '#include "TwPresets.hpp"', '', 'namespace tearwash {', '', 'namespace {']
    table = []
    for i, (name, prog, vals) in enumerate(lib.PRESETS):
        if name in names:
            sys.exit('duplicate preset name: ' + name)
        names.add(name)
        vals = dict(vals)
        # A preset that sets MOD RATE keeps the depth it had before MOD DEPTH existed (excursion × (0.5 + rate),
        # which is 2 × depth × excursion with depth = (0.5 + rate) / 2), unless it sets MOD DEPTH itself.
        if 'modrate' in vals and 'moddepth' not in vals:
            vals['moddepth'] = round((0.5 + vals['modrate']) / 2.0, 6)
        if name[:3] not in ('HL ', 'RM ', 'PL ', 'SP ', 'EC ', 'FX '):
            sys.exit('bad category: ' + name)
        if prog not in programs:
            sys.exit('%s: unknown program %s' % (name, prog))
        items = []
        for k, v in vals.items():
            if k not in keys:
                sys.exit('%s: unknown key %s' % (name, k))
            if not (0.0 <= v <= 1.0) and k not in ('outgain', 'ingain'):
                sys.exit('%s: %s = %r out of range' % (name, k, v))
            items.append((k, v))
        if name in gains:
            items.append(('outgain', round(float(gains[name]), 2)))
        out.append('const TwPresetValue v%d[] = { %s };' % (i, ', '.join('{ "%s", %.10g }' % kv for kv in items)))
        table.append('    { "%s", "%s", v%d, %d },' % (name, prog, i, len(items)))
    out += ['} // namespace', '', 'const TwBuiltinPreset kTwBuiltinPresets[] = {'] + table + ['};',
            'const int kTwBuiltinPresetCount = %d;' % len(table), '', '} // namespace tearwash', '']
    path = os.path.join(ROOT, 'src/tearwash/plugin/TwPresetData.cpp')
    open(path, 'w').write('\n'.join(out))
    stale = sorted(set(gains) - names)
    print('%d presets -> %s (%d with loudness trims%s)' % (len(table), os.path.relpath(path, ROOT), len(names & set(gains)),
                                                          ', stale trims: ' + ', '.join(stale) if stale else ''))


if __name__ == '__main__':
    main()
